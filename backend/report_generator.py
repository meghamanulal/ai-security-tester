    def _generate_nmap_section(self) -> str:
        """Generate Nmap results section"""
        nmap_results = self.scan_results.get('nmap', [])
        
        if not nmap_results:
            return """
            <div class="section">
                <div class="section-header">🔍 OPEN PORTS</div>
                <div class="section-content">
                    <p>No open ports detected or scan failed.</p>
                </div>
            </div>
            """

        rows = ""
        for port_info in nmap_results:
            rows += f"""
            <tr>
                <td>{port_info.get('port', 'N/A')}</td>
                <td>{port_info.get('service', 'N/A')}</td>
                <td>{port_info.get('version', 'N/A')}</td>
            </tr>
            """

        return f"""
        <div class="section">
            <div class="section-header">🔍 OPEN PORTS</div>
            <div class="section-content">
                <table class="port-table">
                    <thead>
                        <tr>
                            <th>Port</th>
                            <th>Service</th>
                            <th>Version</th>
                        </tr>
                    </thead>
                    <tbody>
                        {rows}
                    </tbody>
                </table>
            </div>
        </div>
        """

    def _generate_nikto_section(self) -> str:
        """Generate Nikto results section"""
        nikto_results = self.scan_results.get('nikto', [])
        
        if not nikto_results:
            return """
            <div class="section">
                <div class="section-header">🌐 WEB SERVER FINDINGS</div>
                <div class="section-content">
                    <p>No web vulnerabilities detected by Nikto.</p>
                </div>
            </div>
            """

        findings = ""
        for finding in nikto_results:
            message = finding.get('message', finding.get('msg', 'No description'))
            url = finding.get('url', self.target)
            
            findings += f"""
            <div class="vulnerability medium">
                <h4>🔍 Web Vulnerability</h4>
                <p><strong>URL:</strong> <span class="code">{url}</span></p>
                <p><strong>Issue:</strong> {message}</p>
                {f'<p><strong>Reference:</strong> {finding.get("reference", "")}</p>' if finding.get('reference') else ''}
            </div>
            """

        return f"""
        <div class="section">
            <div class="section-header">🌐 WEB SERVER FINDINGS</div>
            <div class="section-content">
                {findings}
            </div>
        </div>
        """

    def _generate_nuclei_section(self) -> str:
        """Generate Nuclei results section"""
        nuclei_results = self.scan_results.get('nuclei', [])
        
        if not nuclei_results:
            return """
            <div class="section">
                <div class="section-header">⚡ NUCLEI FINDINGS</div>
                <div class="section-content">
                    <p>No vulnerabilities detected by Nuclei.</p>
                </div>
            </div>
            """

        findings = ""
        for finding in nuclei_results:
            severity = finding.get('severity', 'unknown')
            name = finding.get('name', finding.get('template_id', 'Unknown'))
            url = finding.get('url', self.target)
            description = finding.get('description', 'No description available')
            
            findings += f"""
            <div class="vulnerability {severity}">
                <h4>⚡ <span class="severity {severity}">{severity}</span> {name}</h4>
                <p><strong>URL:</strong> <span class="code">{url}</span></p>
                <p><strong>Description:</strong> {description}</p>
                {f'<p><strong>Template ID:</strong> {finding.get("template_id", "")}</p>' if finding.get('template_id') else ''}
            </div>
            """

        return f"""
        <div class="section">
            <div class="section-header">⚡ NUCLEI FINDINGS</div>
            <div class="section-content">
                {findings}
            </div>
        </div>
        """

    def _generate_headers_section(self) -> str:
        """Generate security headers section"""
        headers_result = self.scan_results.get('headers', {})
        
        if 'error' in headers_result:
            return f"""
            <div class="section">
                <div class="section-header">🛡️ SECURITY HEADERS</div>
                <div class="section-content">
                    <p>Failed to analyze security headers: {headers_result['error']}</p>
                </div>
            </div>
            """

        present_headers = headers_result.get('present', {})
        missing_headers = headers_result.get('missing', [])

        present_html = ""
        for header, value in present_headers.items():
            present_html += f"""
            <tr>
                <td class="present-header">{header}</td>
                <td><span class="code">{value}</span></td>
            </tr>
            """

        missing_html = ""
        for header in missing_headers:
            missing_html += f"""
            <tr>
                <td class="missing-header">{header}</td>
                <td>❌ Missing</td>
            </tr>
            """

        return f"""
        <div class="section">
            <div class="section-header">🛡️ SECURITY HEADERS</div>
            <div class="section-content">
                <h3>Present Headers</h3>
                <table class="port-table">
                    <thead>
                        <tr>
                            <th>Header</th>
                            <th>Value</th>
                        </tr>
                    </thead>
                    <tbody>
                        {present_html}
                    </tbody>
                </table>

                <h3 style="margin-top: 30px;">Missing Headers</h3>
                <table class="port-table">
                    <thead>
                        <tr>
                            <th>Header</th>
                            <th>Status</th>
                        </tr>
                    </thead>
                    <tbody>
                        {missing_html}
                    </tbody>
                </table>
            </div>
        </div>
        """
